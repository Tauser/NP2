"""Reproduce the fixed Q15 anti-alias filter; no runtime floating point."""
import argparse
import math
from pathlib import Path

TAPS = 127
CUTOFF = 0.225  # cycles/input sample: 9,922.5 Hz at 44.1 kHz


def source():
    midpoint = (TAPS - 1) // 2
    weights = []
    for i in range(TAPS):
        x = i - midpoint
        sinc = 2 * CUTOFF if x == 0 else math.sin(2 * math.pi * CUTOFF * x) / (math.pi * x)
        weights.append(sinc * (0.54 - 0.46 * math.cos(2 * math.pi * i / (TAPS - 1))))
    scale = sum(weights)
    values = [round(v / scale * 32768) for v in weights]
    values[midpoint] += 32768 - sum(values)
    assert values == values[::-1] and all(-32768 <= v <= 32767 for v in values)
    lines = ["/* Generated by tools/generate_music_fir.py; 127 taps, Hamming, fc=0.225, Q15 sum=32768. */"]
    lines += ["    " + ", ".join(map(str, values[i:i+8])) + "," for i in range(0,TAPS,8)]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "firmware/main/music_fir_q15.inc"
    expected = source()
    if args.check:
        if path.read_text(encoding="utf-8") != expected:
            raise SystemExit("Music FIR is stale")
    else:
        path.write_text(expected, encoding="utf-8")
