"""Generate the small 24 px Material subset; requires fonttools 4.60.1/lv_font_conv 1.5.3.

Source: google/material-design-icons commit 49d4db35df873165d6bd6ba09b063c7dafbac2f4,
variablefont/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf (Apache-2.0).
Usage: python tools/generate_system_material_icons.py SOURCE_TTF LV_FONT_CONV_JS
"""
import hashlib
import pathlib
import subprocess
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

repo = pathlib.Path(__file__).resolve().parent.parent
source = pathlib.Path(sys.argv[1]).resolve()
converter = pathlib.Path(sys.argv[2]).resolve()
assert hashlib.sha256(source.read_bytes()).hexdigest() == (
    "32e4011709e055596eb8d2dd0f7cb547b47c1d40ac9ecb8fad54f7f7eac202e7"
), "Material font source hash differs"
import json
assert json.loads((converter.parent / "package.json").read_text())["version"] == "1.5.3"
font = TTFont(source)
static = instantiateVariableFont(font, {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 400})
static_path = source.with_name("material-rounded-system-static.ttf")
static.save(static_path)
output = repo / "firmware/main/ui/fonts/ui_font_np_material_system_24.c"
# storage, memory (CPU), sd_card, memory_alt (RAM), power_settings_new.
subprocess.run([
    "node", str(converter), "--bpp", "4", "--size", "24", "--no-compress",
    "--font", str(static_path), "--range", "0xe1db,0xe322,0xe623,0xf7a3,0xf8c7",
    "--format", "lvgl", "--output", str(output),
    "--lv-font-name", "ui_font_np_material_system_24", "--lv-include", "lvgl.h",
], check=True)
text = output.read_text(encoding="utf-8")
start, end = text.index(" * Opts:"), text.index("\n", text.index(" * Opts:"))
text = text[:start] + " * Generated by tools/generate_system_material_icons.py; Apache-2.0 source." + text[end:]
output.write_text(text, encoding="utf-8", newline="\n")
